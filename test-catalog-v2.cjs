const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const c=JSON.parse(fs.readFileSync('src/data/catalog.v2.json','utf8'));
 const r=await import('./src/catalog-rules.js');
 assert.deepEqual(r.verifyCatalog(c),{characters:24,arcs:51,items:0,achievements:0,sources:0});
 assert.equal(c.characters.every(x=>x.max_level===80),true);
 assert.equal(c.arcs.every(x=>x.max_tier===5&&x.max_level===80),true);
 assert.equal(c.character_bonds.length,c.characters.length);
 assert.equal(new Set(c.character_bonds.map(x=>x.character_id)).size,24);
 assert.equal(r.defaultProgress('characters').passive_1_unlocked,false);
 assert.equal(r.defaultProgress('characters').passive_2_unlocked,false);
 assert.equal(r.defaultProgress('bonds').bond_level,0);
 assert.equal(r.interactionStatus(false,10,true),'not_available');
 assert.equal(r.interactionStatus(null,10,false),'not_verified');
 assert.equal(r.interactionStatus(true,5,true),'locked');
 assert.equal(r.interactionStatus(true,6,false),'unlocked');
 assert.equal(r.interactionStatus(true,6,true),'done');
 assert.equal(r.acquiredDefaults('arcs',r.defaultProgress('arcs')).tier,1);
 assert.equal('count' in r.defaultProgress('arcs'),false);
 assert.equal(r.parseInteger('80',1,80),80);
 assert.throws(()=>r.parseInteger(81,1,80));
 assert.throws(()=>r.parseInteger(-1,0,6));
 assert.equal(r.parseInteger('',0,null),null);
 assert.equal(r.sourcesFor('x',[{item_id:'x',stage:'3'},{item_id:'y'}]).length,1);
 const rust=fs.readFileSync('src-tauri/src/lib.rs','utf8');
 const profile=fs.readFileSync('src-tauri/src/catalog_profile.rs','utf8');
 const ui=fs.readFileSync('src/catalog-main.js','utf8');
 assert(rust.includes('profile-v2.json')&&rust.includes('data.json'));
 assert(profile.includes('"bonds"'));
 assert(ui.includes("invoke('save_user_progress'"));
 assert(ui.includes('interactions_completed'));
 assert(!ui.includes('r.count='));
 console.log('PASS: stable catalog IDs, category caps, split profile, Bond logic, rarity and backup architecture');
})().catch(e=>{console.error(e);process.exit(1)});
