const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const c=JSON.parse(fs.readFileSync('catalog/catalog.v2.json','utf8'));
 const r=await import('./src/catalog-rules.js');
 const summary=r.verifyCatalog(c);
 assert(summary.characters>=24 && summary.arcs>=51,'The initial roster must not shrink');
 assert.equal(summary.items,c.items.length);
 assert.equal(summary.achievements,c.achievements.length);
 assert.equal(summary.sources,c.item_sources.length);
 assert(Number.isSafeInteger(c.catalogRevision) && c.catalogRevision>=1);
 assert.equal(c.characters.every(x=>x.max_level===80),true);
 assert.equal(c.arcs.every(x=>x.max_tier===5&&x.max_level===80),true);
 assert.equal(c.arcs.filter(x=>x.rarity==='gold').length,30);
 assert.equal(c.arcs.filter(x=>x.rarity==='purple').length,16);
 assert.equal(c.arcs.filter(x=>x.rarity==='blue').length,5);
 assert(c.characters.filter(x=>Object.keys(x.skill_names||{}).length>=7).length>=11);
 assert(c.characters.filter(x=>x.element).length>=20);
 assert(c.catalogRevision>=6);
 assert.equal(c.character_bonds.length,c.characters.length);
 assert.equal(new Set(c.character_bonds.map(x=>x.character_id)).size,c.characters.length);
 assert.equal(r.defaultProgress('characters').passive_1_unlocked,false);
 assert.equal(r.defaultProgress('characters').passive_2_unlocked,false);
 assert.equal(r.defaultProgress('bonds').bond_level,0);
 assert.equal(r.interactionStatus(false,10,true),'not_available');
 assert.equal(r.interactionStatus(null,10,false),'not_verified');
 assert.equal(r.interactionStatus(true,5,true),'locked');
 assert.equal(r.interactionStatus(true,6,false),'unlocked');
 assert.equal(r.interactionStatus(true,6,true),'done');
 assert.equal(r.acquiredDefaults('arcs',r.defaultProgress('arcs')).tier,1);
 assert.equal('count' in r.defaultProgress('arcs'),false);
 assert.equal(r.parseInteger('80',1,80),80);
 assert.throws(()=>r.parseInteger(81,1,80));
 assert.throws(()=>r.parseInteger(-1,0,6));
 assert.equal(r.parseInteger('',0,null),null);
 assert.equal(r.sourcesFor('x',[{item_id:'x',stage:'3'},{item_id:'y'}]).length,1);
 const rust=fs.readFileSync('src-tauri/src/lib.rs','utf8');
 const sync=fs.readFileSync('src-tauri/src/catalog_sync.rs','utf8');
 assert(sync.includes('raw.githubusercontent.com/MrDustyBowl/NTE-Tracker/main/catalog/catalog.v2.json'));
 assert(sync.includes('no_removals') && sync.includes('MAX_BYTES') && sync.includes('fs::rename'));
 assert(rust.includes('sync_game_catalog') && rust.includes('load_game_catalog'));
 assert.throws(()=>r.verifyCatalog({...c,catalogRevision:0}));
 const profile=fs.readFileSync('src-tauri/src/catalog_profile.rs','utf8');
 const ui=fs.readFileSync('src/catalog-main.js','utf8');
 assert(rust.includes('profile-v2.json')&&rust.includes('data.json'));
 assert(profile.includes('"bonds"'));
 assert(ui.includes("invoke('save_user_progress'"));
 assert(ui.includes('interactions_completed'));
 assert(ui.includes('sync_game_catalog') && ui.includes('load_game_catalog'));
 assert(ui.includes('setCatalog(result.catalog,result.source)')); 
 assert(!ui.includes('r.count='));
 console.log('PASS: stable catalog IDs, category caps, live GitHub sync / offline cache, split profile, Bond rules, rarity and backups');
})().catch(e=>{console.error(e);process.exit(1)});
